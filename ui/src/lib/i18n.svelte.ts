/** Reactive: components that read `t()` in markup or `$derived` update when
    the interface language changes. */
const ui = $state<{ lang: 'ru' | 'en' }>({ lang: 'ru' });

export function setLanguage(lang: 'ru' | 'en') {
  ui.lang = lang;
}

export function t(): Strings {
  return ui.lang === 'en' ? en : ru;
}

export function isEnglish(): boolean {
  return ui.lang === 'en';
}

/** Engine display names. */
export function engineName(id: string): string {
  const map: Record<string, string> = {
    google: 'Google',
    yandex: ui.lang === 'en' ? 'Yandex' : 'Яндекс',
    deepl: 'DeepL',
    bing: 'Bing',
    openrouter: 'OpenRouter',
    code: ui.lang === 'en' ? 'Code' : 'Код',
  };
  return map[id] ?? id;
}

/** The grey line under an engine's name. */
export function engineNote(e: { id: string; note?: string }): string {
  return t().engineNote[e.id] ?? e.note ?? '';
}

/** A part of speech as the interface language says it. */
export function posName(pos: string): string {
  return t().pos[pos] ?? pos;
}

/** "161 МБ", "2,5 ГБ" (Russian) or "161 MB", "2.5 GB". */
export function fileSize(bytes: number): string {
  const en = ui.lang === 'en';
  const gb = bytes / 2 ** 30;
  const [n, unit] = gb >= 1 ? [gb.toFixed(1), en ? 'GB' : 'ГБ'] : [String(Math.max(1, Math.round(bytes / 2 ** 20))), en ? 'MB' : 'МБ'];
  return `${en ? n : n.replace('.', ',')} ${unit}`;
}

/** A part of speech, short ("сущ.", "n."). */
export function posShort(pos: string): string {
  return t().posShort[pos] ?? pos;
}
